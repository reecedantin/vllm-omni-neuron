"""Shrunk random-weight pi0 (base) checkpoint (structure test) + its CPU unit tests.

Same intent as ``test_pi0_tiny.py`` (which covers pi0.5 / pi0.52): a real-layout, random-weight,
shrunk checkpoint that proves loading, name mapping, compile and a device forward in minutes.
π0's on-disk layout has no ``model.`` prefix (unlike the LeRobot π0.5 export) and no
``variant_dims`` override exists upstream for π0 — so this generator builds a real
``Pi0ForActionPrediction`` with explicit small Gemma dims via monkeypatched ``get_gemma_config``,
the same technique the real model uses for named variants.

Generate one::

    python test/unit/test_pi0_base_tiny.py --out /path/to/pi0-tiny [--ref /path/to/pi0]
"""

from __future__ import annotations

import argparse
import json
import os

import pytest
import torch

TINY_DIMS = {
    "vision": {
        "hidden_size": 64,
        "intermediate_size": 128,
        "num_hidden_layers": 2,
        "num_attention_heads": 4,
    },
    "paligemma": {
        "width": 64,
        "depth": 2,
        "mlp_dim": 128,
        "num_heads": 8,
        "num_kv_heads": 1,
        "head_dim": 16,
    },
    "action_expert": {
        "width": 32,
        "depth": 2,
        "mlp_dim": 64,
        "num_heads": 8,
        "num_kv_heads": 1,
        "head_dim": 16,
    },
}

_DEFAULT_CONFIG = {
    "type": "pi0",
    "input_features": {
        **{
            f"observation.images.{c}": {"type": "VISUAL", "shape": [3, 224, 224]}
            for c in ("base_0_rgb", "left_wrist_0_rgb", "right_wrist_0_rgb")
        },
        "observation.state": {"type": "STATE", "shape": [32]},
    },
    "output_features": {"action": {"type": "ACTION", "shape": [32]}},
    "paligemma_variant": "gemma_2b",
    "action_expert_variant": "gemma_300m",
    "dtype": "float32",
    "chunk_size": 50,
    "max_state_dim": 32,
    "max_action_dim": 32,
    "num_inference_steps": 10,
    "tokenizer_max_length": 48,
}

# Real lerobot/pi0_base checkpoint dir, for the key-layout test; skipped when unset.
REF_CHECKPOINT = os.environ.get("PI0_WEIGHTS", "")


def make_tiny_checkpoint(
    out_dir: str, ref_dir: str | None = None, seed: int = 0, dims: dict | None = None
) -> str:
    """Write a tiny π0 checkpoint to ``out_dir`` with real structure, random weights."""
    from vllm_omni_neuron.diffusion.models.pi0._vendor.pi0.config import Pi0Config
    from vllm_omni_neuron.diffusion.models.pi0._vendor.pi0.modeling_pi0 import (
        Pi0ForActionPrediction,
    )

    os.makedirs(out_dir, exist_ok=True)
    cfg = dict(_DEFAULT_CONFIG)
    if ref_dir and os.path.exists(os.path.join(ref_dir, "config.json")):
        with open(os.path.join(ref_dir, "config.json")) as f:
            cfg = json.load(f)
    cfg["variant_dims"] = dims or TINY_DIMS
    cfg["device"] = "cpu"
    with open(os.path.join(out_dir, "config.json"), "w") as f:
        json.dump(cfg, f, indent=4)

    torch.manual_seed(seed)
    model = Pi0ForActionPrediction(Pi0Config.from_model_config(cfg))

    with torch.no_grad():
        for name, p in model.named_parameters():
            if p.ndim == 1 and "norm" in name:
                p.normal_(0.0, 0.1)
                if "layer_norm" in name or "post_layernorm" in name:
                    p.add_(1.0 if name.endswith("weight") else 0.0)
            else:
                p.normal_(0.0, 0.02 if p.ndim > 1 else 0.01)
    vt = "paligemma_with_expert.paligemma.model.vision_tower."

    def disk_name(k: str) -> str:  # LeRobot's on-disk SigLIP nesting (transformers <= 5.3)
        if k.startswith(vt) and not k.startswith(vt + "vision_model."):
            k = vt + "vision_model." + k[len(vt) :]
        return k

    state = {
        disk_name(k): v.contiguous().clone()
        for k, v in model.state_dict().items()
        if "rotary_emb" not in k
        and not k.endswith("position_ids")
        and k != "paligemma_with_expert.paligemma.model.language_model.embed_tokens.weight"
    }
    # LeRobot's checkpoint carries gemma_expert's OWN (unused -- gemma_expert.model.embed_tokens is
    # None) lm_head at the ACTION-EXPERT width, not the paligemma embedding width; the model's own
    # randomly-initialized gemma_expert.lm_head.weight already has that shape, so just keep it as-is
    # (it is already in `state` via state_dict() -- no clone-from-elsewhere needed).

    import safetensors.torch

    safetensors.torch.save_file(
        state, os.path.join(out_dir, "model.safetensors"), metadata={"format": "pt"}
    )
    with open(os.path.join(out_dir, "README.md"), "w") as f:
        f.write(
            "Random-weight shrunk pi0 structure-test checkpoint (not a model). "
            "Generated by test/unit/test_pi0_base_tiny.py.\n"
        )
    return out_dir


def _safetensors_keys(path: str) -> dict:
    import struct

    with open(path, "rb") as f:
        n = struct.unpack("<Q", f.read(8))[0]
        header = json.loads(f.read(n))
    header.pop("__metadata__", None)
    return header


