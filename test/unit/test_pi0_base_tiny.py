@pytest.fixture(scope="module")
def tiny_dir(tmp_path_factory):
    ref = REF_CHECKPOINT if os.path.isdir(REF_CHECKPOINT) else None
    return make_tiny_checkpoint(str(tmp_path_factory.mktemp("pi0_tiny")), ref)


def _inputs(cfg, seed=0, n_real_tokens=20, n_real_cams=2):
    g = torch.Generator().manual_seed(seed)
    r = cfg.image_resolution[0]
    images = [torch.rand(1, 3, r, r, generator=g) * 2 - 1 for _ in range(cfg.max_cameras)]
    masks = [torch.tensor([i < n_real_cams]) for i in range(cfg.max_cameras)]
    tokens = torch.zeros(1, cfg.tokenizer_max_length, dtype=torch.long)
    tokens[0, :n_real_tokens] = torch.randint(2, 250000, (n_real_tokens,), generator=g)
    tmask = torch.zeros(1, cfg.tokenizer_max_length, dtype=torch.bool)
    tmask[0, :n_real_tokens] = True
    state = torch.rand(1, cfg.max_state_dim, generator=g) * 2 - 1
    noise = torch.randn(1, cfg.chunk_size, cfg.max_action_dim, generator=g)
    return images, masks, tokens, tmask, state, noise


def test_tiny_key_layout_matches_real(tiny_dir):
    if not os.path.isdir(REF_CHECKPOINT):
        pytest.skip("real pi0 checkpoint not present")
    import re

    tiny = _safetensors_keys(os.path.join(tiny_dir, "model.safetensors"))
    real = _safetensors_keys(os.path.join(REF_CHECKPOINT, "model.safetensors"))

    def keep(k):
        m = re.search(r"\.layers\.(\d+)\.", k)
        return m is None or int(m.group(1)) < 2

    assert set(tiny) == {k for k in real if keep(k)}
    assert all(tiny[k]["dtype"] == real[k]["dtype"] for k in tiny)


def test_tiny_loads_strict(tiny_dir):
    """π0's load_weights warns rather than raises on a mismatch; check completeness via its
    returned filled-params set instead of expecting an exception."""
    import safetensors.torch

    from vllm_omni_neuron.diffusion.models.pi0 import NeuronPi0ActionModel
    from vllm_omni_neuron.diffusion.models.pi0._vendor.pi0.config import Pi0Config

    cfg = Pi0Config.from_pretrained(tiny_dir)
    m = NeuronPi0ActionModel(cfg, dtype=torch.float32)
    state = safetensors.torch.load_file(os.path.join(tiny_dir, "model.safetensors"))
    filled = m.ref.load_weights(state.items())
    params = {
        n
        for n, _ in m.ref.named_parameters()
        if "rotary_emb" not in n and not n.endswith(".inv_freq")
    }
    assert params <= filled, sorted(params - filled)[:10]


@pytest.mark.parametrize("n_real_cams", [3, 1])
def test_graphs_match_upstream_fp32(tiny_dir, n_real_cams):
    """The fixed-shape graphs reproduce the vendored upstream pi0 model exactly in fp32."""
    from vllm_omni_neuron.diffusion.models.pi0 import NeuronPi0ActionModel
    from vllm_omni_neuron.diffusion.models.pi0._vendor.pi0.config import Pi0Config

    cfg = Pi0Config.from_pretrained(tiny_dir)
    m = NeuronPi0ActionModel(cfg, dtype=torch.float32)
    m.load_checkpoint(tiny_dir)
    images, masks, tokens, tmask, state, noise = _inputs(cfg, n_real_cams=n_real_cams)
    with torch.no_grad():
        ref = m.ref.sample_actions(images, masks, tokens, tmask, state, noise=noise.clone())
        out = m.sample_actions(images, masks, tokens, tmask, state, noise=noise.clone())
    rel = ((out - ref).norm() / ref.norm()).item()
    assert out.shape == (1, cfg.chunk_size, cfg.max_action_dim)
    assert rel < 1e-5, rel


def test_graphs_bf16_close(tiny_dir):
    from vllm_omni_neuron.diffusion.models.pi0 import NeuronPi0ActionModel
    from vllm_omni_neuron.diffusion.models.pi0._vendor.pi0.config import Pi0Config

    cfg = Pi0Config.from_pretrained(tiny_dir)
    m32 = NeuronPi0ActionModel(cfg, dtype=torch.float32)
    m32.load_checkpoint(tiny_dir)
    m16 = NeuronPi0ActionModel(cfg, dtype=torch.bfloat16)
    m16.load_checkpoint(tiny_dir)
    images, masks, tokens, tmask, state, noise = _inputs(cfg)
    with torch.no_grad():
        a = m32.sample_actions(images, masks, tokens, tmask, state, noise=noise.clone())
        b = m16.sample_actions(images, masks, tokens, tmask, state, noise=noise.clone())
    rel = ((a - b).norm() / a.norm()).item()
    assert rel < 0.05, rel


def test_prefix_kv_ignores_padding(tiny_dir):
    from vllm_omni_neuron.diffusion.models.pi0 import NeuronPi0ActionModel
    from vllm_omni_neuron.diffusion.models.pi0._vendor.pi0.config import Pi0Config

    cfg = Pi0Config.from_pretrained(tiny_dir)
    m = NeuronPi0ActionModel(cfg, dtype=torch.float32)
    m.load_checkpoint(tiny_dir)
    images, masks, tokens, tmask, state, noise = _inputs(cfg, n_real_cams=2)
    with torch.no_grad():
        a = m.sample_actions(images, masks, tokens, tmask, state, noise=noise.clone())
        tokens2 = tokens.clone()
        tokens2[0, 30:] = 12345
        images2 = list(images)
        images2[2] = torch.zeros_like(images[2])
        b = m.sample_actions(images2, masks, tokens2, tmask, state, noise=noise.clone())
    assert torch.allclose(a, b, atol=1e-6, rtol=0)


def test_pipeline_end_to_end_cpu(tiny_dir):
    """NeuronPi0Pipeline registers, builds from a checkpoint dir and turns a raw robot observation
    into the same action chunk as the vendored upstream model given the same noise."""
    import dataclasses
    import types

    tok_dir = os.path.join(os.environ.get("WEIGHTS", ""), "paligemma-3b-pt-224")
    if not os.path.isdir(tok_dir):
        pytest.skip("PaliGemma tokenizer not present (set WEIGHTS)")

    from vllm_omni.diffusion.data import OmniDiffusionConfig

    import vllm_omni_neuron
    from vllm_omni_neuron.diffusion.models.pi0 import PIPELINE_REGISTRY, NeuronPi0Pipeline
    from vllm_omni_neuron.diffusion.models.pi0._vendor.pi0.processor_pi0 import build_model_inputs

    vllm_omni_neuron._register_pipelines()
    assert {"Pi0Pipeline", "pi0", "Pi05Pipeline", "pi052"} <= {
        e["model_arch"] for e in PIPELINE_REGISTRY
    }

    od = OmniDiffusionConfig.__new__(OmniDiffusionConfig)
    for f in dataclasses.fields(OmniDiffusionConfig):
        setattr(od, f.name, None)
    od.model, od.dtype, od.model_config = tiny_dir, "float32", {}
    od.model_config = {"tokenizer": tok_dir}
    pipe = NeuronPi0Pipeline(od_config=od)

    g = torch.Generator().manual_seed(0)
    cams = [k for k in pipe.config.input_features if "image" in k]
    obs = {
        "prompt": "pick up the red cube",
        **{k: torch.rand(224, 224, 3, generator=g).numpy() for k in cams},
        "state": (torch.rand(pipe.config.max_state_dim, generator=g) * 2 - 1).numpy(),
    }
    noise = torch.randn(1, pipe.config.chunk_size, pipe.config.max_action_dim, generator=g)
    sp = types.SimpleNamespace(
        extra_args={"robot_obs": obs, "noise": noise.clone()}, num_inference_steps=4
    )
    out = pipe.forward(types.SimpleNamespace(sampling_params=sp, prompts=[]))
    assert out.error is None, out.error
    a = torch.from_numpy(out.output["actions"])
    assert a.shape == (pipe.config.chunk_size, pipe.config.max_action_dim)

    im, mk, lt, lm, st = build_model_inputs(obs, pipe.config, pipe.tokenizer, torch.device("cpu"))
    with torch.no_grad():
        ref = pipe.model.ref.sample_actions(im, mk, lt, lm, st, noise=noise.clone(), num_steps=4)[0]
    assert ((a - ref).norm() / ref.norm()).item() < 1e-5


@pytest.mark.parametrize("mode", ["unrolled", "host"])
def test_denoise_modes_match_default(tiny_dir, mode):
    """pi0's per-step device Euler loop (default) == the unrolled graph == the host loop."""
    from vllm_omni_neuron.diffusion.models.pi0 import NeuronPi0ActionModel
    from vllm_omni_neuron.diffusion.models.pi0._vendor.pi0.config import Pi0Config

    cfg = Pi0Config.from_pretrained(tiny_dir)
    m = NeuronPi0ActionModel(cfg, dtype=torch.float32)
    m.load_checkpoint(tiny_dir)
    images, masks, tokens, tmask, state, noise = _inputs(cfg)
    with torch.no_grad():
        a = m.sample_actions(images, masks, tokens, tmask, state, noise=noise.clone(), num_steps=5)
        m.denoise_loop.mode = mode
        b = m.sample_actions(images, masks, tokens, tmask, state, noise=noise.clone(), num_steps=5)
    assert torch.allclose(a, b, atol=1e-6, rtol=0), (a - b).abs().max()


